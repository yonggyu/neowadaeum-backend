-- V4 — 기본 엔딩 계약 (#52, §13-16 결정 반영)
--
-- §13-16 은 두 가지가 규정되지 않았음을 지적했다 — ① 기본 엔딩이 condition 을 가질 수 있는가
-- ② 일반 엔딩이 condition 없이 존재할 수 있는가. S-4 초안에는 이 CHECK 가 있었으나 원문에
-- 근거가 없어 제거했고, 그래서 지금은 "조건 없는 일반 엔딩"이 저장될 수 있다.
--
-- 그런 행이 하나라도 들어가면 R7.6 의 ending_no 순회에서 **항상 최초 매칭**이 되어 뒤의 엔딩을
-- 전부 가린다. 증상은 "엔딩이 하나밖에 안 나온다"로 보이고, 원인이 데이터라는 것을 찾는 데 시간이 든다.
--
-- ── 결정 (2026-08-23) ───────────────────────────────────────
--   1. is_default = true  → condition 을 갖지 않는다
--   2. is_default = false → condition 을 반드시 갖는다
--   3. 기본 엔딩은 R7.7 의 시점에만 선택된다 —
--      마지막 챕터에서 max_turns 에 도달했고 조건부 엔딩이 하나도 매칭되지 않았을 때.
--      **매 턴 "미매칭이면 기본 엔딩"이 아니다.** 그렇게 읽으면 초반 턴은 어떤 조건도
--      만족하지 않으므로 모든 세션이 1턴에 끝난다.
--   4. 엔딩 집합에 기본 엔딩은 **정확히 1개** (R2.2 유지)
--   5. DB 는 ≤ 1 을 보장하고, ≥ 1 은 **작품이 플레이 가능한 상태로 전환될 때**
--      애플리케이션이 검증한다
--
-- 1 과 2 는 아래 CHECK 하나로 정확히 표현된다.
-- 3 은 엔진 동작이므로 S-7 의 몫이다.
-- 4 의 상한은 V2 의 ending_def_one_default_per_version partial unique 가 이미 강제한다.
--
-- **하한(≥ 1)은 여기서 강제할 수 없다.** 행의 부재는 CHECK 로 볼 수 없고, 트리거로 막으면
-- 작성 도중의 정상 상태(엔딩을 아직 안 만든 draft)까지 거부하게 된다. 그래서 검증 시점을
-- "플레이 가능한 상태로 전환될 때"로 잡았다 — 그 순간이 R2.2 의 "무한히 진행되는 세션 방지"가
-- 실제로 의미를 갖는 시점이다.

ALTER TABLE ending_def ADD CONSTRAINT ending_def_default_has_no_condition_check
    CHECK (is_default = (condition IS NULL));
