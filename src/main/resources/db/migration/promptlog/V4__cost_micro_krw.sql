-- V4 — cost_micro 의 통화를 이름이 말하게 한다 (#311, §13-53)
--
-- 컬럼은 "백만분의 1" 만 말하고 **무엇의 백만분의 1인지**는 어디에도 없었다 — 엔티티에도,
-- 이 마이그레이션의 원본(V2)에도, 계약에도, 설정에도 없었다. 벤더 단가가 USD 로 고시되므로
-- 통화를 정하지 않은 채 어댑터마다 채우면 한쪽은 USD, 한쪽은 KRW 가 되고 합계는 뜻을 잃는다.
--
-- 통화는 KRW 로 정했다. 환율은 서버에 두지 않는다 — 설정에 넣는 단가 자체가 KRW 이며,
-- 환산은 그 값을 넣는 사람이 한다. 서버가 환율을 들면 그 값이 낡는 순간부터 조용히 틀린 수가
-- 쌓이고, 쌓인 뒤에는 어느 시점 환율로 계산됐는지 알 수 없다.
--
-- **백필이 없다.** 지금 이 컬럼의 값은 전부 NULL 이다 — 어느 Provider 도 채우지 않았다
-- (Anthropic 은 단가표가 없어서, Ollama 는 로컬 실행이라 개념이 없어서). 그래서 되돌릴 값이
-- 없고, 이름만 바꾸면 통화가 섞인 행이 존재할 수 없다. 값이 쌓인 뒤였다면 각 행이 어느 통화로
-- 기록됐는지 사후에 알 방법이 없었을 것이다.
--
-- IF EXISTS 를 쓰지 않는다. 없다면 전제가 틀린 것이고, 그 사실이 드러나야 한다.
ALTER TABLE ai_call_log RENAME COLUMN cost_micro TO cost_micro_krw;

COMMENT ON COLUMN ai_call_log.cost_micro_krw IS
    '호출 비용. 원(KRW)의 백만분의 1 단위다. 단가를 모르면 NULL 이며, 지어낸 0 을 넣지 않는다.';
