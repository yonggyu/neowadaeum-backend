#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────
# check-env-drift.sh — .env.example 에는 있는데 .env 에는 없는 키를 알린다 (#434, #489, §7.2)
#
#   ./scripts/check-env-drift.sh
#
# `.env` 는 `.gitignore` 대상이라 추적되지 않는다(§7.2). 그래서 **예시 파일에 키가 늘어도
# 각자의 사본이 따라왔는지 아무도 대조하지 않는다** — 새 기능이 새 변수를 들일 때 커밋되는 것은
# `.env.example` 뿐이고, 이미 사본을 만들어 둔 사람의 `.env` 는 그 자리에 멈춰 있다.
#
# ── 왜 여기인가 (이슈 #434 의 결정 1) ────────────────────────
# `.env` 는 클래스패스 리소스가 아니라 **레포 루트의 파일**이다. ApplicationTemplateBindingTests
# 는 같은 종류의 대조를 클래스패스에서 하는데, 그 이유를 자기 주석에 적어 두었다 — 상대 경로로
# 레포 루트를 찾으면 워크트리·CI 에서 작업 디렉터리가 달라져 **검사 대상이 아니라 검사 자신이
# 실패한다.** `.env` 에는 클래스패스로 가는 길이 없으므로 그 자리를 쓸 수 없다.
#
# ── 왜 이 방향인가 (결정 2) ──────────────────────────────────
# 예시에만 있는 키 = **사본이 낡았다**. 그 반대(사본에만 있는 키)는 보지 않는다.
#
# ApplicationTemplateBindingTests 는 정확히 반대 방향을 본다. 거기서 낡는 쪽은 템플릿이다 —
# `application.yml` 은 **구조를 담은 설정 파일**이라 사람이 로컬에서 키를 더해 가며 쓰고, 그렇게
# 앞서 나간 사본의 지식은 그 사본을 가진 한 명에게만 남는다(#428 의 `spring.config.import` 가
# 그렇게 3개월을 살았다).
#
# `.env` 는 그 성질이 아니다. **키=값 목록일 뿐 구조가 없고**, 사본에 새 키가 생기는 것은
# `application.yml` 이 `${VAR}` 로 그 이름을 부를 때뿐이다 — 그리고 그 호출은 추적되는 파일에
# 들어오므로 `.env.example` 과 함께 온다. 즉 **사본이 앞서 나가는 일이 거의 없고, 있어도 읽는
# 곳이 없어 무해하다.** 반대로 예시가 앞서 나가는 것은 기능이 늘 때마다 일어나고, 그 어긋남은
# 그 기능을 처음 부르는 날까지 조용하다.
#
# ── 무엇이 막고 무엇이 알리는가 (#489 — 결정 4 를 대체한다) ──
# 처음에는 **전부 알리기만 했다.** 빠진 키가 전부 부팅을 세우는 것은 아니므로 한 덩어리로 묶어
# 막을 수 없었기 때문이다. 그러나 그 결과는 **아무것도 막지 않는 검사**였고, `#489` 가 그것을
# 관측했다 — 경고가 났고, 테스트는 전부 통과했고, 아무 일도 일어나지 않았다.
#
# 그래서 **키를 둘로 나눈다.** 나누는 자리는 이 스크립트가 아니라 `.env.example` 이다 —
# 키를 더하는 사람이 그 자리에서 판단해 `# [required]` / `# [optional]` 표시를 붙이고, 여기서는
# 그 표시를 읽기만 한다. 목록을 스크립트에 복사해 두면 **반드시 어긋나고**, 어긋난 쪽은
# 언제나 예시가 아니라 숨어 있는 이 파일이 된다.
#
#   필수 — 없으면 앱이 뜨지 않는다(부팅 중 검증되거나 로컬 인프라가 그 값으로 뜬다). **exit 1.**
#          "값이 없으면 부팅을 실패시킨다"(§7.1-3)는 규칙과 같은 줄에 서는 것이 요점이다 —
#          부팅에서 실패할 것을 푸시 전에 말한다.
#   선택 — 그 기능을 켤 때 채운다. 없으면 그 경로만 죽는다. **알리고 통과한다(exit 0).**
#          여기서 막으면 값을 구하지 못한 새 사람이 시작조차 하지 못한다.
#
# 표시 규칙: 줄이 정확히 `# [required]` / `# [optional]` 로 **시작할 때만** 표시로 본다(본문
# 가운데의 같은 낱말은 표시가 아니다 — 그 규약을 설명하는 문장이 표시로 읽히면 안 된다).
# 표시는 다음 표시까지 이어지고, **표시 앞의 키는 필수로 읽는다** — 잊고 더한 키가 조용히
# 선택이 되는 것보다 시끄럽게 필수가 되는 편이 낫다.
#
# ── 값을 읽지 않는다 (결정 3, S-11) ──────────────────────────
# 두 파일에서 꺼내는 것은 `=` **앞**뿐이다. `.env` 에는 실제 자격 증명이 들어 있고, 값을 한 번
# 읽으면 그것이 터미널·스크롤백·CI 로그에 남는다 (S-3). 키 이름만으로 이 결함은 전부 잡힌다.
#
# ── 파일이 없는 환경 ─────────────────────────────────────────
# `.env` 가 없으면(CI·갓 클론한 레포) 대조할 사본이 없으므로 그 사실만 알리고 0 으로 끝낸다 —
# **#489 이후에도 그대로다.** CI 에는 `.env` 가 없고, 없는 것은 낡은 것과 다르다.
# `.env.example` 이 없으면 그것은 환경 문제가 아니라 **레포의 결함**이므로 1 로 끝낸다.
# ─────────────────────────────────────────────────────────────
set -euo pipefail

cd "$(dirname "$0")/.."

EXAMPLE=".env.example"
COPY=".env"

# `=` 앞의 이름만 꺼낸다. 값은 패턴에 담지도 출력하지도 않는다 (S-11).
# 주석(`# FOO=`)은 걸리지 않는다 — 주석 처리된 키는 설정되지 않은 것이다.
keys() {
	sed -n 's/^[[:space:]]*\(export[[:space:]][[:space:]]*\)\{0,1\}\([A-Za-z_][A-Za-z0-9_]*\)=.*/\2/p' "$1" \
		| sort -u
}

# 예시 파일의 키를 `# [required]` / `# [optional]` 표시로 나눈다. 값은 보지 않는다 (S-11).
example_keys() {
	# mode 의 초기값이 required 다 — 표시가 나오기 전의 키는 필수로 읽는다(위 "표시 규칙").
	awk -v want="$1" -v mode=required '
		/^# \[required\]/ { mode = "required"; next }
		/^# \[optional\]/ { mode = "optional"; next }
		/^[[:space:]]*#/  { next }
		{
			line = $0
			sub(/^[[:space:]]+/, "", line)
			sub(/^export[[:space:]]+/, "", line)
			if (line ~ /^[A-Za-z_][A-Za-z0-9_]*=/ && mode == want) {
				print substr(line, 1, index(line, "=") - 1)
			}
		}
	' "$EXAMPLE" | sort -u
}

list() {
	while IFS= read -r key; do
		printf "$1" "$key"
	done <<< "$2"
}

if [ ! -f "$EXAMPLE" ]; then
	printf '\033[31m✗ %s 가 없다. 추적되는 파일이므로 이것은 레포의 결함이다.\033[0m\n' "$EXAMPLE" >&2
	exit 1
fi

if [ ! -f "$COPY" ]; then
	printf '  %s 가 없다 — 대조할 사본이 없는 환경이다(CI·갓 클론한 레포). 만드는 법: cp %s %s\n' \
		"$COPY" "$EXAMPLE" "$COPY"
	exit 0
fi

present="$(keys "$COPY")"
missing_required="$(comm -23 <(example_keys required) <(printf '%s\n' "$present"))"
missing_optional="$(comm -23 <(example_keys optional) <(printf '%s\n' "$present"))"

if [ -n "$missing_optional" ]; then
	printf '\033[33m  ! %s 에는 있는데 %s 에는 없는 **선택** 키:\033[0m\n' "$EXAMPLE" "$COPY"
	list '\033[33m      %s\033[0m\n' "$missing_optional"
	printf '\033[33m    막지 않는다 — 그 기능을 켜는 날 채운다. 없으면 그 경로만 죽고 부팅은 된다.\033[0m\n'
fi

if [ -n "$missing_required" ]; then
	printf '\033[31m✗ %s 에는 있는데 %s 에는 없는 **필수** 키:\033[0m\n' "$EXAMPLE" "$COPY" >&2
	list '\033[31m      %s\033[0m\n' "$missing_required" >&2
	printf '\033[31m  이 키가 없으면 앱이 뜨지 않는다. %s 에서 그 줄을 가져와 값을 채운다 —\n' "$EXAMPLE" >&2
	printf '  값은 이 레포에 없다 (S-11). 필수/선택 구분은 %s 의 표시가 정한다 (#489).\033[0m\n' "$EXAMPLE" >&2
	exit 1
fi

if [ -z "$missing_optional" ]; then
	printf '  %s 의 키가 %s 에 전부 있다.\n' "$EXAMPLE" "$COPY"
else
	printf '  %s 의 **필수** 키는 %s 에 전부 있다.\n' "$EXAMPLE" "$COPY"
fi
exit 0
